# y_true shape: (batch_size, 2) -> [PnL_Long, PnL_Short]
# y_pred shape: (batch_size, 2) -> [Prob_Long, Prob_Short]
def profit_loss(y_true, y_pred):
    pnl_long = y_true[:, 0]
    pnl_short = y_true[:, 1]
    
    prob_long = y_pred[:, 0]
    prob_short = y_pred[:, 1]
    
    # Expected Profit = (Probability of Long * PnL of Long) + (Probability of Short * PnL of Short)
    expected_profit = (prob_long * pnl_long) + (prob_short * pnl_short)
    
    # Loss is the negative expected profit (Keras minimizes loss)
    # We add a small entropy regularization to prevent it from predicting [0, 0, 1] (Hold forever) instantly.
    entropy = -tf.reduce_mean(y_pred * tf.math.log(y_pred + 1e-9))
    
    return -tf.reduce_mean(expected_profit) - 0.01 * entropy

def win_rate_metric(y_true, y_pred):
    pnl_long = y_true[:, 0]
    pnl_short = y_true[:, 1]
    prob_long = y_pred[:, 0]
    prob_short = y_pred[:, 1]
    
    taken_long = tf.cast(prob_long > 0.55, tf.float32)
    taken_short = tf.cast(prob_short > 0.55, tf.float32)
    
    profit = (taken_long * pnl_long) + (taken_short * pnl_short)
    
    wins = tf.reduce_sum(tf.cast(profit > 0, tf.float32))
    losses = tf.reduce_sum(tf.cast(profit < 0, tf.float32))
    
    return wins / (wins + losses + 1e-9)

def total_profit_metric(y_true, y_pred):
    pnl_long = y_true[:, 0]
    pnl_short = y_true[:, 1]
    prob_long = y_pred[:, 0]
    prob_short = y_pred[:, 1]
    
    taken_long = tf.cast(prob_long > 0.55, tf.float32)
    taken_short = tf.cast(prob_short > 0.55, tf.float32)
    
    profit = (taken_long * pnl_long) + (taken_short * pnl_short)
    return tf.reduce_sum(profit)

WINDOW_SIZE = 30
LSTM_UNITS = 96

inp = Input(shape=(WINDOW_SIZE, 11), name="input_1")
lstm1 = LSTM(LSTM_UNITS, return_sequences=True, name="lstm_LSTM1")(inp)
bn1 = BatchNormalization(name="batch_normalization_BatchNormalization1")(lstm1)
do1 = Dropout(0.3, name="dropout_1")(bn1)

lstm2 = LSTM(LSTM_UNITS, return_sequences=False, name="lstm_LSTM2")(do1)
bn2 = BatchNormalization(name="batch_normalization_BatchNormalization2")(lstm2)
do2 = Dropout(0.3, name="dropout_2")(bn2)

d1 = Dense(32, activation='relu', kernel_regularizer=l2(1e-4), name="dense_Dense1")(do2)
do3 = Dropout(0.3, name="dropout_3")(d1)
d2 = Dense(16, activation='relu', kernel_regularizer=l2(1e-4), name="dense_Dense2")(do3)

# Now we output 2 values with Softmax: [Prob_Long, Prob_Short]
action_out = Dense(2, activation='softmax', name="actionOutput")(d2)

model = Model(inputs=inp, outputs=action_out)

optimizer = tf.keras.optimizers.Adam(learning_rate=0.001)
model.compile(optimizer=optimizer, loss=profit_loss, metrics=[win_rate_metric, total_profit_metric])

# We replaced LoopUntilProfitable with EarlyStopping
early_stop = EarlyStopping(
    monitor='val_total_profit_metric', 
    mode='max', 
    patience=15, 
    restore_best_weights=True,
    verbose=1
)

def export_weights(model, filename):
    with open(filename, 'w') as f:
        f.write('//+------------------------------------------------------------------+\n')
        f.write('//|                                                   CATWeights.mqh |\n')
        f.write('//|                        AUTO-GENERATED BY PYTHON EXPORTER (KERAS) |\n')
        f.write('//+------------------------------------------------------------------+\n\n')

        for layer in model.layers:
            weights = layer.get_weights()
            if len(weights) == 0:
                continue

            for i, w in enumerate(weights):
                w_flat = w.flatten()
                shape_str = ', '.join(map(str, w.shape))
                
                f.write(f'// Layer: {layer.name}, Shape: [{shape_str}]\n')
                f.write(f'double {layer.name}_w{i}[{len(w_flat)}] = {{\n    ')
                
                line_items = []
                for idx, val in enumerate(w_flat):
                    line_items.append(f"{val:.8f}")
                    if len(line_items) == 10:
                        f.write(', '.join(line_items))
                        if idx < len(w_flat) - 1:
                            f.write(',\n    ')
                        line_items = []
                
                if line_items:
                    f.write(', '.join(line_items))
                f.write('\n};\n\n')

class HotExportCallback(tf.keras.callbacks.Callback):
    def __init__(self, filepath):
        super().__init__()
        self.filepath = filepath
        
    def on_epoch_end(self, epoch, logs=None):
        export_weights(self.model, self.filepath)
        print(f"💾 Pesi esportati in {self.filepath} a caldo (Fine Epoca {epoch+1})")

print("Inizio Addestramento (Reinforcement Learning) ...")
model.fit(X_features, Y_pnl, epochs=150, batch_size=256, validation_split=0.2, callbacks=[early_stop, HotExportCallback('../../CATWeights.mqh')])

export_weights(model, '../../CATWeights.mqh')
print("✅ Addestramento Terminato. CATWeights.mqh salvato con successo!")

